"""Phase-7 advisory CI eval gate.

The gate is intentionally narrow:

- it runs only the tracked, hand-written mini-set (``data/miniset.jsonl``);
- it runs only the ``haiku-agent`` arm at the final Phase-3 effort (``low``);
- it scores with the deterministic MATCH_SPEC v1.1 scorer; and
- it never uses a judge verdict.

It is **advisory**. A missing key, a failed run, or a cost-ceiling stop is
reported in the pull-request comment; the command itself exits 0. Pytest
failures are a separate job and still fail normally.

The baseline is a small committed JSON document generated by a deliberate
manual run. This module can write it, but the CI workflow never does.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Mapping, Sequence

from eval.config import (
    MATCH_SPEC_VERSION,
    MAX_TOKENS,
    MINI_SET_PATH,
    model_id_for,
)
from eval.harness import RunAborted, run_arms
from eval.metrics import TokenPrice, load_pricing_file

GATE_ARM = "haiku-agent"
GATE_EFFORT = "low"
GATE_COST_CEILING_USD = 0.25
GATE_REPEATS = 1
GATE_PRICING_PATH = "config/pricing.list_sync.2026-10-31.json"
GATE_BASELINE_PATH = "baselines/phase7-miniset-haiku-low.json"
COMMENT_MARKER = "<!-- phase7-eval-gate:comment -->"
BASELINE_SCHEMA_VERSION = 1

REPO_ROOT = Path(__file__).resolve().parents[2]


class GateError(ValueError):
    """The gate was asked to do something outside its advisory scope."""


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _repo_path(path: Path | str) -> Path:
    candidate = Path(path)
    return candidate if candidate.is_absolute() else REPO_ROOT / candidate


def _miniset_case_count(path: Path | str = MINI_SET_PATH) -> int:
    try:
        return sum(
            1 for line in _repo_path(path).read_text().splitlines() if line.strip()
        )
    except OSError:
        return 0


def sha256_file(path: Path | str) -> str:
    """Return the SHA-256 of a file, or an empty string when it is absent."""

    candidate = Path(path)
    if not candidate.exists():
        return ""
    return hashlib.sha256(candidate.read_bytes()).hexdigest()


def _mean(values: Sequence[float]) -> float:
    return sum(values) / len(values) if values else 0.0


def _count_exact_cases(cases: Mapping[str, Mapping[str, Any]]) -> int:
    return sum(
        1
        for case in cases.values()
        if abs(_as_float(case.get("exact")) - 1.0) < 1e-9
    )


def _as_float(value: Any, default: float = 0.0) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return default
    return float(value)


def _as_int(value: Any, default: int = 0) -> int:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return default
    return int(value)


def extract_arm_payload(
    payload: Mapping[str, Any],
    *,
    arm: str = GATE_ARM,
) -> tuple[Mapping[str, Any], Mapping[str, Any]]:
    """Return ``(arm_payload, outer_run)`` from combined or single-arm JSON."""

    if not isinstance(payload, Mapping):
        raise GateError("results payload must be a JSON object")

    arms = payload.get("arms")
    if isinstance(arms, Mapping) and arm in arms:
        arm_payload = arms[arm]
        if not isinstance(arm_payload, Mapping):
            raise GateError(f"arm payload for {arm!r} must be an object")
        outer_run = payload.get("run")
        return arm_payload, outer_run if isinstance(outer_run, Mapping) else {}

    if "per_case" in payload and "summary" in payload:
        run_block = payload.get("run")
        return payload, run_block if isinstance(run_block, Mapping) else {}

    raise GateError(f"results payload has no arm {arm!r}")


def view_from_payload(
    payload: Mapping[str, Any],
    *,
    arm: str = GATE_ARM,
    miniset_path: Path | str = MINI_SET_PATH,
    pricing_path: str = GATE_PRICING_PATH,
) -> dict[str, Any]:
    """Turn harness results JSON into the small view the comment needs."""

    arm_payload, outer_run = extract_arm_payload(payload, arm=arm)
    run = dict(outer_run)
    run.update(dict(arm_payload.get("run") or {}))
    summary = dict(arm_payload.get("summary") or {})
    records = list(arm_payload.get("per_case") or [])

    grouped: dict[str, list[Mapping[str, Any]]] = {}
    for record in records:
        if str(record.get("status", "completed")) != "completed":
            continue
        grouped.setdefault(str(record["task_id"]), []).append(record)

    cases: dict[str, dict[str, float]] = {}
    for task_id, rows in grouped.items():
        cases[task_id] = {
            "exact": _mean([_as_float(row.get("exact")) for row in rows]),
            "partial": _mean([_as_float(row.get("partial")) for row in rows]),
        }

    n_cases = _as_int(summary.get("n_cases"), len(cases))
    exact_mean = _as_float(summary.get("exact_match_mean"))
    partial_mean = _as_float(summary.get("partial_mean"))
    if "exact_match_mean" not in summary and cases:
        exact_mean = _mean([case["exact"] for case in cases.values()])
    if "partial_mean" not in summary and cases:
        partial_mean = _mean([case["partial"] for case in cases.values()])
    cost_total = _as_float(summary.get("cost_usd_total"))
    if "cost_usd_total" not in summary:
        cost_total = sum(_as_float(record.get("cost_usd")) for record in records)

    return {
        "run_id": str(run.get("run_id", "")),
        "git_commit": str(run.get("git_commit", "")),
        "arm": arm,
        "model_id": str(run.get("model_id", "")),
        "effort": str(run.get("effort", GATE_EFFORT)),
        "max_tokens": _as_int(run.get("max_tokens"), MAX_TOKENS),
        "match_spec_version": str(
            run.get("match_spec_version", MATCH_SPEC_VERSION)
        ),
        "prompt_version": str(run.get("prompt_version", "")),
        "pricing_file": str(run.get("pricing_path") or pricing_path),
        "pricing_basis": str(run.get("pricing_basis", "list_sync")),
        "miniset_path": str(miniset_path),
        "miniset_sha256": sha256_file(_repo_path(miniset_path)),
        "n_cases": n_cases,
        "n_cases_completed": _as_int(
            summary.get("n_cases_completed"), len(cases)
        ),
        "n_cases_aborted": _as_int(summary.get("n_cases_aborted")),
        "exact_match_mean": exact_mean,
        "exact_matches": _count_exact_cases(cases),
        "partial_mean": partial_mean,
        "cost_usd_total": cost_total,
        "cost_ceiling_usd": _as_float(
            run.get("cost_ceiling_usd"), GATE_COST_CEILING_USD
        ),
        "format_failure_rate": _as_float(summary.get("format_failure_rate")),
        "format_failure_breakdown": dict(
            summary.get("format_failure_breakdown") or {}
        ),
        "run_status": str(run.get("run_status", "completed")),
        "abort_reason": run.get("abort_reason"),
        "cases": cases,
    }


def baseline_from_view(view: Mapping[str, Any], *, source_run_id: str = "") -> dict[str, Any]:
    """Build the committed baseline document from one completed view."""

    return {
        "schema_version": BASELINE_SCHEMA_VERSION,
        "generated_at": _now_iso(),
        "source_run_id": source_run_id or str(view.get("run_id", "")),
        "git_commit": str(view.get("git_commit", "")),
        "arm": str(view.get("arm", GATE_ARM)),
        "model_id": str(view.get("model_id", "")),
        "effort": str(view.get("effort", GATE_EFFORT)),
        "max_tokens": _as_int(view.get("max_tokens"), MAX_TOKENS),
        "match_spec_version": str(
            view.get("match_spec_version", MATCH_SPEC_VERSION)
        ),
        "prompt_version": str(view.get("prompt_version", "")),
        "pricing_file": str(view.get("pricing_file", GATE_PRICING_PATH)),
        "pricing_basis": str(view.get("pricing_basis", "list_sync")),
        "miniset_path": str(view.get("miniset_path", MINI_SET_PATH)),
        "miniset_sha256": str(view.get("miniset_sha256", "")),
        "n_cases": _as_int(view.get("n_cases")),
        "exact_match_mean": _as_float(view.get("exact_match_mean")),
        "partial_mean": _as_float(view.get("partial_mean")),
        "cost_usd_total": _as_float(view.get("cost_usd_total")),
        "cases": {
            str(case_id): {
                "exact": _as_float(case.get("exact")),
                "partial": _as_float(case.get("partial")),
            }
            for case_id, case in dict(view.get("cases") or {}).items()
        },
    }


def write_baseline_from_payload(
    payload: Mapping[str, Any],
    baseline_path: Path | str = GATE_BASELINE_PATH,
    *,
    miniset_path: Path | str = MINI_SET_PATH,
    pricing_path: str = GATE_PRICING_PATH,
    force: bool = False,
) -> dict[str, Any]:
    """Write a baseline from saved results. This is a deliberate manual act."""

    view = view_from_payload(
        payload,
        miniset_path=miniset_path,
        pricing_path=pricing_path,
    )
    if view.get("run_status") != "completed":
        raise GateError(
            "refusing to write a baseline from an incomplete run: "
            f"{view.get('run_status')!r}"
        )
    if not view.get("cases"):
        raise GateError("refusing to write a baseline with no completed cases")

    destination = Path(baseline_path)
    if destination.exists() and not force:
        raise GateError(
            f"baseline already exists: {destination}; pass --force to replace it"
        )

    baseline = baseline_from_view(view)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(baseline, indent=2, sort_keys=True) + "\n")
    return baseline


def load_baseline(path: Path | str = GATE_BASELINE_PATH) -> dict[str, Any] | None:
    """Load the committed baseline, or return ``None`` when it is absent."""

    candidate = Path(path)
    if not candidate.exists():
        return None
    payload = json.loads(candidate.read_text())
    if not isinstance(payload, dict):
        raise GateError(f"baseline {candidate} must contain a JSON object")
    return payload


def compare_to_baseline(
    view: Mapping[str, Any],
    baseline: Mapping[str, Any] | None,
    *,
    tolerance: float = 1e-9,
) -> dict[str, Any] | None:
    """Compare one run view with the stored baseline.

    Returns ``None`` when no baseline exists. Otherwise the result carries the
    aggregate deltas, the configuration mismatches that make a baseline
    incomparable, and every per-case change keyed by case id.
    """

    if baseline is None:
        return None

    checks = (
        ("arm", "arm"),
        ("model_id", "model id"),
        ("effort", "effort"),
        ("max_tokens", "max_tokens"),
        ("match_spec_version", "MATCH_SPEC version"),
        ("pricing_file", "pricing file"),
        ("pricing_basis", "pricing basis"),
        ("miniset_path", "mini-set path"),
        ("miniset_sha256", "mini-set checksum"),
    )
    mismatches: list[dict[str, Any]] = []
    for key, label in checks:
        expected = baseline.get(key)
        actual = view.get(key)
        if expected != actual:
            mismatches.append(
                {"field": label, "baseline": expected, "run": actual}
            )

    baseline_cases = dict(baseline.get("cases") or {})
    run_cases = dict(view.get("cases") or {})
    changes: list[dict[str, Any]] = []
    for case_id in sorted(set(baseline_cases) | set(run_cases)):
        if case_id not in run_cases:
            changes.append({"id": case_id, "kind": "missing_from_run"})
            continue
        if case_id not in baseline_cases:
            changes.append({"id": case_id, "kind": "new_case"})
            continue

        base_case = baseline_cases[case_id]
        run_case = run_cases[case_id]
        base_exact = _as_float(base_case.get("exact"))
        run_exact = _as_float(run_case.get("exact"))
        base_partial = _as_float(base_case.get("partial"))
        run_partial = _as_float(run_case.get("partial"))
        if (
            abs(base_exact - run_exact) > tolerance
            or abs(base_partial - run_partial) > tolerance
        ):
            changes.append(
                {
                    "id": case_id,
                    "kind": "changed",
                    "baseline_exact": base_exact,
                    "run_exact": run_exact,
                    "baseline_partial": base_partial,
                    "run_partial": run_partial,
                }
            )

    return {
        "compatible": not mismatches,
        "mismatches": mismatches,
        "exact_delta": _as_float(view.get("exact_match_mean"))
        - _as_float(baseline.get("exact_match_mean")),
        "partial_delta": _as_float(view.get("partial_mean"))
        - _as_float(baseline.get("partial_mean")),
        "cost_delta": _as_float(view.get("cost_usd_total"))
        - _as_float(baseline.get("cost_usd_total")),
        "changes": changes,
    }


def _pct(value: Any) -> str:
    return f"{100.0 * _as_float(value):.1f}%"


def _score_cell(mean: Any, matches: int, n_cases: int) -> str:
    return f"{_pct(mean)} ({matches}/{n_cases})"


def _points_delta(value: Any) -> str:
    return f"{100.0 * _as_float(value):+.2f} pts"


def _money(value: Any) -> str:
    return f"${_as_float(value):.6f}"


def _money_delta(value: Any) -> str:
    amount = _as_float(value)
    sign = "+" if amount >= 0 else "-"
    return f"{sign}${abs(amount):.6f}"


def _expected_config() -> dict[str, Any]:
    return {
        "arm": GATE_ARM,
        "model_id": model_id_for(GATE_ARM),
        "effort": GATE_EFFORT,
        "max_tokens": MAX_TOKENS,
        "match_spec_version": MATCH_SPEC_VERSION,
        "pricing_file": GATE_PRICING_PATH,
        "pricing_basis": "list_sync",
        "miniset_path": MINI_SET_PATH,
    }


def _config_table(view: Mapping[str, Any] | None) -> list[str]:
    config = dict(_expected_config())
    if view is not None:
        config.update(
            {
                key: view.get(key)
                for key in config
                if view.get(key) is not None
            }
        )
        cases = view.get("n_cases")
        checksum = str(view.get("miniset_sha256", ""))
    else:
        cases = _miniset_case_count()
        checksum = sha256_file(_repo_path(MINI_SET_PATH))

    effort = str(config.get("effort"))
    effort_label = (
        f"`{effort}` (`output_config.effort`)"
        if effort != "api_default"
        else "`api_default` (no effort field)"
    )
    case_label = f"`{config.get('miniset_path')}` ({cases} cases"
    if checksum:
        case_label += f"; sha256 `{checksum[:16]}…`"
    case_label += "; held-out test split not run)"
    ceiling = GATE_COST_CEILING_USD
    if view is not None:
        ceiling = _as_float(view.get("cost_ceiling_usd"), GATE_COST_CEILING_USD)

    return [
        "### Configuration",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Arm | `{config.get('arm')}` |",
        f"| Model | `{config.get('model_id')}` |",
        f"| Effort | {effort_label} |",
        f"| max_tokens | {config.get('max_tokens')} |",
        f"| Scoring | MATCH_SPEC `{config.get('match_spec_version')}` "
        "(deterministic scorer; no judge) |",
        f"| Case set | {case_label} |",
        f"| Pricing | `{config.get('pricing_file')}` "
        f"(`{config.get('pricing_basis')}`) |",
        f"| Cost ceiling | {_money(ceiling)} |",
    ]


def render_comment(
    *,
    status: str,
    view: Mapping[str, Any] | None = None,
    baseline: Mapping[str, Any] | None = None,
    diff: Mapping[str, Any] | None = None,
    message: str | None = None,
    baseline_path: Path | str = GATE_BASELINE_PATH,
) -> str:
    """Render the exact PR comment for one gate outcome."""

    lines = [
        COMMENT_MARKER,
        "",
        "## Eval gate (advisory)",
        "",
        "_Scorer-based, mini-set only. No judge verdicts are used. "
        "This check never fails the build._",
        "",
    ]

    result_line = {
        "completed": "**Result:** completed.",
        "completed_with_failures": (
            "**Result:** completed with failures (reported, not build-failing)."
        ),
        "cost_ceiling": "**Result:** stopped at the cost ceiling.",
        "skipped": "**Result:** skipped.",
        "failed": "**Result:** failed (reported, not build-failing).",
    }.get(status, f"**Result:** {status}.")
    lines.append(result_line)
    if message:
        lines.extend(["", message])

    if view is not None:
        n_cases = _as_int(view.get("n_cases"))
        run_exact = _score_cell(
            view.get("exact_match_mean"),
            _as_int(view.get("exact_matches")),
            n_cases,
        )
        lines.extend(["", "### Scores", ""])
        if baseline is None:
            lines.extend(
                [
                    "| Metric | This run | Baseline | Change |",
                    "|---|---:|---:|---:|",
                    f"| Exact match | {run_exact} | — | — |",
                    f"| Partial | {_pct(view.get('partial_mean'))} | — | — |",
                    f"| List-price cost | {_money(view.get('cost_usd_total'))} "
                    "| — | — |",
                ]
            )
        else:
            baseline_exact = _score_cell(
                baseline.get("exact_match_mean"),
                _count_exact(baseline),
                _as_int(baseline.get("n_cases")),
            )
            lines.extend(
                [
                    "| Metric | This run | Baseline | Change |",
                    "|---|---:|---:|---:|",
                    f"| Exact match | {run_exact} | {baseline_exact} "
                    f"| {_points_delta((diff or {}).get('exact_delta'))} |",
                    f"| Partial | {_pct(view.get('partial_mean'))} "
                    f"| {_pct(baseline.get('partial_mean'))} "
                    f"| {_points_delta((diff or {}).get('partial_delta'))} |",
                    f"| List-price cost | {_money(view.get('cost_usd_total'))} "
                    f"| {_money(baseline.get('cost_usd_total'))} "
                    f"| {_money_delta((diff or {}).get('cost_delta'))} |",
                ]
            )

        aborted = _as_int(view.get("n_cases_aborted"))
        format_rate = _as_float(view.get("format_failure_rate"))
        if aborted or format_rate:
            lines.extend(
                [
                    "",
                    f"Diagnostics: {aborted} aborted case(s); "
                    f"format-failure rate {_pct(format_rate)}.",
                ]
            )
            breakdown = dict(view.get("format_failure_breakdown") or {})
            if breakdown:
                rendered = ", ".join(
                    f"`{kind}` {count}"
                    for kind, count in sorted(breakdown.items())
                )
                lines.append(f"Format failures: {rendered}.")

        if diff is not None and not diff.get("compatible", True):
            lines.extend(
                [
                    "",
                    "**Baseline mismatch.** This run is not directly comparable "
                    "to the stored baseline:",
                ]
            )
            for mismatch in diff.get("mismatches", []):
                lines.append(
                    f"- {mismatch.get('field')}: baseline "
                    f"`{mismatch.get('baseline')}` vs run `{mismatch.get('run')}`"
                )
            lines.append(
                "Per-case changes are still listed below for information only."
            )
    elif status == "skipped":
        lines.extend(
            [
                "",
                "No run scores are available. No API calls were made and no "
                "cost was incurred.",
            ]
        )
    elif status == "failed":
        lines.extend(
            [
                "",
                "No run scores are available. The failure is reported here; "
                "the job log has the detail. The build is unaffected.",
            ]
        )

    if baseline is None:
        lines.extend(
            [
                "",
                f"**Baseline:** `{baseline_path}` is missing. The comment "
                "reports the run without a diff.",
            ]
        )
    elif view is not None:
        lines.extend(["", "### Per-case changes vs baseline", ""])
        changes = list((diff or {}).get("changes", []))
        if not changes:
            lines.append("- No per-case changes.")
        else:
            lines.extend(
                [
                    "| Case | Exact | Partial |",
                    "|---|---:|---:|",
                ]
            )
            for change in changes:
                case_id = str(change.get("id"))
                if change.get("kind") == "changed":
                    lines.append(
                        f"| `{case_id}` | "
                        f"{_as_float(change.get('baseline_exact')):.0f} → "
                        f"{_as_float(change.get('run_exact')):.0f} | "
                        f"{_as_float(change.get('baseline_partial')):.2f} → "
                        f"{_as_float(change.get('run_partial')):.2f} |"
                    )
                elif change.get("kind") == "missing_from_run":
                    lines.append(f"| `{case_id}` | missing from run | missing from run |")
                else:
                    lines.append(f"| `{case_id}` | not in baseline | not in baseline |")

    lines.extend(["", *_config_table(view)])
    lines.extend(
        [
            "",
            "---",
            "_Advisory by design: this gate does not fail a build, and no judge "
            "verdict is used anywhere. It is a mini-set smoke detector, not a "
            "headline result. Baseline regeneration is a manual, documented "
            "act; CI never writes the baseline._",
        ]
    )
    return "\n".join(lines) + "\n"


def _count_exact(baseline: Mapping[str, Any]) -> int:
    return _count_exact_cases(dict(baseline.get("cases") or {}))


def _status_from_view(view: Mapping[str, Any]) -> str:
    if str(view.get("run_status", "completed")) == "aborted":
        return "cost_ceiling"
    if _as_int(view.get("n_cases_completed")) == 0:
        return "completed_with_failures"
    if _as_float(view.get("format_failure_rate")) >= 1.0:
        return "completed_with_failures"
    return "completed"


def _read_run_results(run_dir: Path) -> Mapping[str, Any] | None:
    for candidate in (run_dir / "results.json", run_dir / GATE_ARM / "results.json"):
        if not candidate.exists():
            continue
        try:
            payload = json.loads(candidate.read_text())
        except (OSError, json.JSONDecodeError):
            continue
        if isinstance(payload, Mapping):
            return payload
    return None


def _assert_miniset_only(subset_path: Path | str) -> None:
    resolved = _repo_path(subset_path).resolve()
    expected = _repo_path(MINI_SET_PATH).resolve()
    if resolved != expected:
        raise GateError(
            "the eval gate is mini-set only and refuses to run "
            f"{subset_path!r}; expected {MINI_SET_PATH!r}"
        )


def run_gate(
    *,
    out_dir: Path | str = "results/ci-eval-gate",
    subset_path: Path | str = MINI_SET_PATH,
    pricing_path: str = GATE_PRICING_PATH,
    cost_ceiling: float = GATE_COST_CEILING_USD,
    run_id: str | None = None,
    client: Any = None,
    pricing: Mapping[str, TokenPrice] | None = None,
    api_key_present: bool | None = None,
) -> tuple[str, dict[str, Any] | None, str | None]:
    """Run the advisory gate and return ``(status, view, message)``.

    ``client``, ``pricing``, and ``api_key_present`` are injectable for offline
    tests. A live run requires the real environment key and the pinned pricing
    file.
    """

    if api_key_present is None:
        api_key_present = bool(os.environ.get("ANTHROPIC_API_KEY"))
    if not api_key_present:
        return (
            "skipped",
            None,
            "`ANTHROPIC_API_KEY` is not configured for this workflow run "
            "(fork pull requests do not receive repository secrets). No API "
            "calls were made and no cost was incurred.",
        )

    if cost_ceiling <= 0 or cost_ceiling > GATE_COST_CEILING_USD:
        raise GateError(
            f"gate cost ceiling must be > 0 and <= {GATE_COST_CEILING_USD:.2f}"
        )
    _assert_miniset_only(subset_path)

    if run_id is None:
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        run_id = f"phase7-gate-{stamp}-{uuid.uuid4().hex[:8]}"

    table = (
        pricing
        if pricing is not None
        else load_pricing_file(Path(pricing_path))
    )

    try:
        result = run_arms(
            subset_path,
            out_dir,
            [GATE_ARM],
            client=client,
            pricing=table,
            cost_ceiling=cost_ceiling,
            repeats=GATE_REPEATS,
            run_id=run_id,
            pricing_path=pricing_path,
            efforts={GATE_ARM: GATE_EFFORT},
        )
    except RunAborted as exc:
        run_dir = Path(exc.result["run_dir"])
        payload = _read_run_results(run_dir)
        view = (
            view_from_payload(payload, miniset_path=subset_path, pricing_path=pricing_path)
            if payload is not None
            else None
        )
        reason = str(exc)
        return (
            "cost_ceiling",
            view,
            f"The harness stopped at the hard {_money(cost_ceiling)} per-run "
            f"ceiling. Partial results are shown when available. Reason: "
            f"`{reason}`.",
        )
    except Exception as exc:  # pragma: no cover - defensive CI reporting
        payload = _read_run_results(Path(out_dir) / str(run_id))
        view = (
            view_from_payload(
                payload,
                miniset_path=subset_path,
                pricing_path=pricing_path,
            )
            if payload is not None
            else None
        )
        return (
            "failed",
            view,
            f"The eval gate could not complete: `{type(exc).__name__}: {exc}`. "
            "The build is unaffected because this gate is advisory.",
        )

    run_dir = Path(result["run_dir"])
    payload = _read_run_results(run_dir)
    if payload is None:
        return (
            "failed",
            None,
            "The eval gate finished but produced no readable `results.json`. "
            "The build is unaffected because this gate is advisory.",
        )

    view = view_from_payload(
        payload,
        miniset_path=subset_path,
        pricing_path=pricing_path,
    )
    status = _status_from_view(view)
    if status != "completed":
        return (
            status,
            view,
            "One or more cases failed; see the diagnostics below.",
        )
    return status, view, None


def _write_comment(path: Path, body: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Phase-7 advisory CI eval gate (scorer-based, mini-set only)"
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="render the comment from a saved results file; make no API call",
    )
    parser.add_argument(
        "--write-baseline",
        action="store_true",
        help="write the committed baseline from a saved completed results file",
    )
    parser.add_argument(
        "--results",
        default=None,
        help="saved results JSON for --dry-run or --write-baseline",
    )
    parser.add_argument(
        "--baseline",
        default=GATE_BASELINE_PATH,
        help=f"stored baseline path (default: {GATE_BASELINE_PATH})",
    )
    parser.add_argument(
        "--out-comment",
        default="eval-gate-comment.md",
        help="where to write the rendered PR comment",
    )
    parser.add_argument(
        "--out",
        default="results/ci-eval-gate",
        help="output directory for a live run",
    )
    parser.add_argument("--run-id", default=None, help="optional live run id")
    parser.add_argument(
        "--pricing-file",
        default=GATE_PRICING_PATH,
        help=f"pinned list-price file (default: {GATE_PRICING_PATH})",
    )
    parser.add_argument(
        "--cost-ceiling",
        type=float,
        default=GATE_COST_CEILING_USD,
        help=f"hard per-run ceiling (max {GATE_COST_CEILING_USD:.2f})",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="replace an existing baseline when used with --write-baseline",
    )
    args = parser.parse_args(argv)

    comment_path = Path(args.out_comment)

    if args.dry_run:
        if not args.results:
            parser.error("--dry-run requires --results")
        payload = json.loads(Path(args.results).read_text())
        view = view_from_payload(
            payload,
            miniset_path=MINI_SET_PATH,
            pricing_path=args.pricing_file,
        )
        baseline = load_baseline(args.baseline)
        diff = compare_to_baseline(view, baseline)
        status = _status_from_view(view)
        message = None
        if status == "cost_ceiling":
            message = (
                "Saved results report an aborted run: "
                f"`{view.get('abort_reason')}`."
            )
        elif status == "completed_with_failures":
            message = "Saved results report failed cases; see diagnostics."
        body = render_comment(
            status=status,
            view=view,
            baseline=baseline,
            diff=diff,
            message=message,
            baseline_path=args.baseline,
        )
        _write_comment(comment_path, body)
        print(body)
        print(f"Wrote {comment_path}")
        return 0

    if args.write_baseline:
        if not args.results:
            parser.error("--write-baseline requires --results")
        payload = json.loads(Path(args.results).read_text())
        baseline = write_baseline_from_payload(
            payload,
            args.baseline,
            miniset_path=MINI_SET_PATH,
            pricing_path=args.pricing_file,
            force=args.force,
        )
        print(
            json.dumps(
                {
                    "baseline": str(args.baseline),
                    "model_id": baseline["model_id"],
                    "effort": baseline["effort"],
                    "miniset_sha256": baseline["miniset_sha256"],
                    "n_cases": baseline["n_cases"],
                    "exact_match_mean": baseline["exact_match_mean"],
                    "partial_mean": baseline["partial_mean"],
                    "cost_usd_total": baseline["cost_usd_total"],
                },
                indent=2,
            )
        )
        return 0

    status = "failed"
    view: dict[str, Any] | None = None
    message: str | None = None
    try:
        status, view, message = run_gate(
            out_dir=args.out,
            pricing_path=args.pricing_file,
            cost_ceiling=args.cost_ceiling,
            run_id=args.run_id,
        )
        baseline = load_baseline(args.baseline)
        diff = compare_to_baseline(view, baseline) if view is not None else None
        body = render_comment(
            status=status,
            view=view,
            baseline=baseline,
            diff=diff,
            message=message,
            baseline_path=args.baseline,
        )
    except Exception as exc:  # pragma: no cover - defensive CI reporting
        status = "failed"
        view = None
        message = (
            f"The eval gate could not complete: `{type(exc).__name__}: {exc}`. "
            "The build is unaffected because this gate is advisory."
        )
        body = render_comment(
            status=status,
            view=None,
            baseline=None,
            message=message,
            baseline_path=args.baseline,
        )

    try:
        _write_comment(comment_path, body)
        print(f"Eval gate status: {status}")
        print(f"Wrote {comment_path}")
    except OSError as exc:  # pragma: no cover - filesystem guard
        # The workflow has a fallback comment step; never turn this into a
        # red build.
        print(f"Eval gate could not write {comment_path}: {exc}")
    return 0


